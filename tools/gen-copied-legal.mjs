#!/usr/bin/env node
/**
 * gen-copied-legal.mjs — license notice for the copy-only vendored assets.
 *
 * Sibling of gen-vendor-legal.mjs, which handles the esbuild BUNDLE. This one
 * handles everything the build merely `cp`s out of node_modules: xterm, marked,
 * dompurify, highlight.js and github-markdown-css.
 *
 * Why it exists: the same reason. `cp node_modules/xterm/lib/xterm.js .` copies
 * the code and leaves node_modules/xterm/LICENSE behind, and MIT's "shall be
 * included in all copies" doesn't care whether the copy came from a bundler or
 * from cp(1). Six of the nine files this covers carry no inline banner at all —
 * they express their grant purely as a LICENSE file — so without this they ship
 * with no notice anywhere.
 *
 * Unlike the bundle script there's no metafile to read: the copies are literal
 * `cp` commands in package.json, so the file → package mapping is declared
 * below and MUST be updated when a build:* script starts copying something new.
 * The script fails loudly on any vendored file it can't account for, which is
 * what keeps that from being a silent omission.
 *
 * Usage:  node gen-copied-legal.mjs ../src/painapple_code/static/vendor/LICENSES.txt
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const VENDOR = new URL('../src/painapple_code/static/vendor/', import.meta.url).pathname;
const NODE_MODULES = new URL('./node_modules/', import.meta.url).pathname;

// vendored filename → { pkg, src } — the npm package it was copied from and
// the path within that package, so we can check the copy is still current.
const ORIGIN = {
    'xterm.js': { pkg: 'xterm', src: 'lib/xterm.js' },
    'xterm.css': { pkg: 'xterm', src: 'css/xterm.css' },
    'xterm-addon-fit.js': { pkg: 'xterm-addon-fit', src: 'lib/xterm-addon-fit.js' },
    'marked.min.js': { pkg: 'marked', src: 'marked.min.js' },
    'purify.min.js': { pkg: 'dompurify', src: 'dist/purify.min.js' },
    'highlight.min.js': { pkg: '@highlightjs/cdn-assets', src: 'highlight.min.js' },
    'highlight-github-dark.min.css': {
        pkg: '@highlightjs/cdn-assets',
        src: 'styles/github-dark.min.css',
    },
    'highlight-lang-dockerfile.min.js': {
        pkg: '@highlightjs/cdn-assets',
        src: 'languages/dockerfile.min.js',
    },
    'highlight-lang-scala.min.js': {
        pkg: '@highlightjs/cdn-assets',
        src: 'languages/scala.min.js',
    },
    'highlight-lang-nginx.min.js': {
        pkg: '@highlightjs/cdn-assets',
        src: 'languages/nginx.min.js',
    },
    'highlight-lang-properties.min.js': {
        pkg: '@highlightjs/cdn-assets',
        src: 'languages/properties.min.js',
    },
    'github-markdown-dark.min.css': {
        pkg: 'github-markdown-css',
        src: 'github-markdown-dark.css',
    },
};

// Generated elsewhere or not third-party — accounted for, deliberately not here.
const NOT_COPIED = {
    'codemirror.js': 'esbuild bundle — see codemirror.js.LEGAL.txt',
    'codemirror.js.LEGAL.txt': 'generated by gen-vendor-legal.mjs',
    'LICENSES.txt': 'this file',
    'README.md': 'our own documentation',
};

const outPath = process.argv[2] || join(VENDOR, 'LICENSES.txt');

// Guard against a new `cp` landing a file here that nobody records a license
// for. Silence is the failure mode this whole script exists to prevent, so an
// unknown file is an error, not a warning.
const unaccounted = readdirSync(VENDOR).filter((f) => !(f in ORIGIN) && !(f in NOT_COPIED));
if (unaccounted.length) {
    console.error(
        `gen-copied-legal: unrecognised file(s) in static/vendor/: ${unaccounted.join(', ')}\n` +
            '  Add each to ORIGIN (with the npm package it came from) or to NOT_COPIED.'
    );
    process.exit(1);
}

// The version numbers below are read from node_modules, but the notice
// describes the file sitting in static/vendor/ — and those are only the same
// thing if the copy is current. A hand-reverted or hand-patched vendored file
// would make this notice quietly misstate what actually ships, so compare them
// and say so. A warning, not an error: after a normal `npm run build` the
// copies have just been made, and a mismatch here is a stale-artifact problem
// to fix deliberately, not a reason to break the build.
function driftReport() {
    const drifted = [];
    for (const [file, { pkg, src }] of Object.entries(ORIGIN)) {
        const digest = (p) => {
            try {
                return createHash('sha256').update(readFileSync(p)).digest('hex');
            } catch {
                return null;
            }
        };
        const vendored = digest(join(VENDOR, file));
        const upstream = digest(join(NODE_MODULES, pkg, src));
        if (vendored && upstream && vendored !== upstream) drifted.push({ file, pkg });
    }
    return drifted;
}

/** Every LICENSE* file a package ships — dompurify has two (Apache-2.0 + MPL-2.0). */
function licenseFiles(pkgDir) {
    return readdirSync(pkgDir)
        .filter((f) => /^licen[sc]e/i.test(f))
        .sort();
}

function manifest(pkgDir) {
    try {
        return JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
    } catch {
        return {};
    }
}

const packages = [...new Set(Object.values(ORIGIN).map((o) => o.pkg))].sort();
const records = [];
const missing = [];

for (const name of packages) {
    const dir = join(NODE_MODULES, name);
    let files;
    try {
        files = licenseFiles(dir);
    } catch {
        console.error(
            `gen-copied-legal: ${name} is not installed under tools/node_modules.\n` +
                '  Run `npm install` in tools/ before regenerating.'
        );
        process.exit(1);
    }
    const meta = manifest(dir);
    const consumers = Object.entries(ORIGIN)
        .filter(([, o]) => o.pkg === name)
        .map(([f]) => f);
    if (!files.length) missing.push(name);
    records.push({
        name,
        version: meta.version || '',
        license: meta.license || 'UNKNOWN',
        consumers,
        texts: files.map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').trim() })),
    });
}

const out = [];
out.push('Third-party license notices for the copied assets in this directory.');
out.push('');
out.push('Generated by tools/gen-copied-legal.mjs. Covers the files the build');
out.push('copies verbatim out of node_modules; the esbuild bundle is covered');
out.push('separately by codemirror.js.LEGAL.txt.');
out.push('');
out.push('It exists because copying a file out of a package leaves that package\'s');
out.push('LICENSE behind, and these licenses require their copyright notice to');
out.push('travel with the code. Most of these files carry no inline banner.');
out.push('');
out.push('Do not edit by hand — rerun the build.');
out.push('');
out.push(`Packages: ${records.length}`);
out.push('');
for (const r of records) {
    out.push(`  ${r.name}${r.version ? `@${r.version}` : ''} — ${r.license}`);
    for (const f of r.consumers) out.push(`      ${f}`);
}
out.push('');

for (const [i, r] of records.entries()) {
    out.push('='.repeat(72));
    out.push(`(${i + 1}) ${r.name}${r.version ? `@${r.version}` : ''} — ${r.license}`);
    out.push(`    Applies to: ${r.consumers.join(', ')}`);
    out.push('='.repeat(72));
    out.push('');
    for (const t of r.texts) {
        // dompurify ships Apache-2.0 AND MPL-2.0; naming the file makes it
        // obvious the notice below is one of several, not the whole grant.
        if (r.texts.length > 1) {
            out.push(`--- ${t.file} ---`);
            out.push('');
        }
        out.push(t.text);
        out.push('');
    }
}

if (missing.length) {
    out.push('='.repeat(72));
    out.push('Packages shipping no LICENSE file');
    out.push('='.repeat(72));
    out.push('');
    out.push('Their declared SPDX license is listed above; the canonical text was');
    out.push('not published in the package tarball.');
    out.push('');
    for (const name of missing) out.push(`  ${name}`);
    out.push('');
}

writeFileSync(outPath, out.join('\n'));
console.log(
    `gen-copied-legal: ${records.length} packages / ${Object.keys(ORIGIN).length} files -> ${outPath}` +
        (missing.length ? ` (${missing.length} without LICENSE text)` : '')
);

const drifted = driftReport();
if (drifted.length) {
    console.error('\ngen-copied-legal: WARNING — vendored file(s) differ from node_modules:');
    for (const d of drifted) console.error(`  ${d.file}  (${d.pkg})`);
    console.error(
        '\n  The version numbers in the notice come from node_modules, so they now\n' +
            '  describe something other than what ships. Either re-run the copy step,\n' +
            '  or pin the dependency to the version actually vendored.\n'
    );
}
