#!/usr/bin/env node
/**
 * gen-vendor-legal.mjs — emit the license notice that ships beside a bundle.
 *
 * Why this exists: esbuild's --legal-comments only relocates comments that are
 * IN the source (`/*!`, `@license`, `@preserve`). The @codemirror/* packages
 * carry none — they express their MIT grant as a LICENSE file per package.
 * Bundling therefore drops the copyright notices entirely, while MIT requires
 * that "the above copyright notice ... be included in all copies or
 * substantial portions of the Software". A minified 1 MB bundle of 20 MIT
 * packages with no notice anywhere is exactly what that clause is about.
 *
 * So we reconstruct the notice from the packages actually bundled. The input
 * is esbuild's --metafile, which lists every resolved input path, so the set
 * is what really went in rather than what package.json happens to declare
 * (devDependencies include build-only tools; transitive deps like @lezer/*
 * are pulled in without being declared at all).
 *
 * Usage:
 *   esbuild ... --metafile=meta.json
 *   node gen-vendor-legal.mjs meta.json ../path/to/bundle.js.LEGAL.txt
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const [, , metaPath, outPath] = process.argv;
if (!metaPath || !outPath) {
    console.error('usage: gen-vendor-legal.mjs <metafile.json> <out.LEGAL.txt>');
    process.exit(1);
}

const meta = JSON.parse(readFileSync(metaPath, 'utf8'));

/**
 * Input paths look like "node_modules/@codemirror/view/dist/index.js" or
 * "node_modules/style-mod/src/style-mod.js". Take the package name, honouring
 * the @scope/name form, and keep the node_modules root so nested installs
 * (node_modules/a/node_modules/b) resolve to the copy actually used.
 */
function packageOf(inputPath) {
    const idx = inputPath.lastIndexOf('node_modules/');
    if (idx === -1) return null;
    const root = inputPath.slice(0, idx + 'node_modules/'.length);
    const rest = inputPath.slice(idx + 'node_modules/'.length);
    const parts = rest.split('/');
    const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
    return { name, dir: join(root, name) };
}

const packages = new Map();
for (const inputPath of Object.keys(meta.inputs || {})) {
    const pkg = packageOf(inputPath);
    if (pkg && !packages.has(pkg.name)) packages.set(pkg.name, pkg.dir);
}

if (packages.size === 0) {
    console.error('gen-vendor-legal: no node_modules inputs found in metafile');
    process.exit(1);
}

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE'];

function readLicenseText(dir) {
    for (const candidate of LICENSE_FILES) {
        try {
            return readFileSync(join(dir, candidate), 'utf8').trim();
        } catch {
            /* try next */
        }
    }
    return null;
}

function readManifest(dir) {
    try {
        return JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    } catch {
        return {};
    }
}

const base = dirname(resolve(metaPath));
const entries = [];
const missing = [];

for (const name of [...packages.keys()].sort()) {
    const dir = resolve(base, packages.get(name));
    const manifest = readManifest(dir);
    const text = readLicenseText(dir);
    const license =
        manifest.license ||
        (Array.isArray(manifest.licenses) ? manifest.licenses.map((l) => l.type).join(' OR ') : '') ||
        'UNKNOWN';
    if (!text) missing.push(name);
    entries.push({ name, version: manifest.version || '', license, text });
}

// Identical MIT texts repeated 30x is noise nobody reads. Group packages by
// their exact license text so the file stays scannable: one text, many
// packages. The summary table above it is what you actually audit from.
const byText = new Map();
for (const e of entries) {
    if (!e.text) continue;
    if (!byText.has(e.text)) byText.set(e.text, []);
    byText.get(e.text).push(e);
}

const lines = [];
lines.push('Third-party license notices for this bundle.');
lines.push('');
lines.push('This file is generated by tools/gen-vendor-legal.mjs from the packages');
lines.push('esbuild actually bundled (its --metafile input list). It exists because');
lines.push('bundling discards each package\'s LICENSE file, and the licenses below');
lines.push('require their copyright notices to travel with the code.');
lines.push('');
lines.push('Do not edit by hand — rerun the build.');
lines.push('');
lines.push(`Packages bundled: ${entries.length}`);
lines.push('');
for (const e of entries) {
    lines.push(`  ${e.name}${e.version ? `@${e.version}` : ''} — ${e.license}`);
}
lines.push('');

let n = 0;
for (const [text, group] of byText) {
    n += 1;
    lines.push('='.repeat(72));
    lines.push(`(${n}) Applies to: ${group.map((g) => g.name).join(', ')}`);
    lines.push('='.repeat(72));
    lines.push('');
    lines.push(text);
    lines.push('');
}

if (missing.length) {
    lines.push('='.repeat(72));
    lines.push('Packages with no LICENSE file in their published tarball');
    lines.push('='.repeat(72));
    lines.push('');
    lines.push('Their declared SPDX license is listed above; the canonical text was');
    lines.push('not shipped by the package itself.');
    lines.push('');
    for (const name of missing) lines.push(`  ${name}`);
    lines.push('');
}

writeFileSync(outPath, lines.join('\n'));
console.log(
    `gen-vendor-legal: ${entries.length} packages -> ${outPath}` +
        (missing.length ? ` (${missing.length} without LICENSE text)` : '')
);
